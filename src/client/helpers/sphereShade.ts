import * as PIXI from 'pixi.js';

/**
 * Стекло поверх кружка игрока — того самого «яйца», которым он сидит за столом.
 *
 * Под ним лицо игрока (см. BadgeBody), поэтому кружок и не должен читаться
 * шариком: это слегка выпуклый значок под стеклом. Отсюда и всё, что здесь
 * рисуется, — отсвет тонкой дугой по верхней левой кромке, узкая тёмная кайма по
 * дальней от света стороне и белый рефлекс под ней. Середина остаётся нетронутой:
 * любое пятно поверх неё мылит и лицо, и картинку карты статуса.
 *
 * Ложится оно одинаково на всех: и на лицо, и на цветной кружок, и на картинку
 * статуса (нечто, заражение — см. StatusSkin). Поэтому свет за столом у всех с
 * одной стороны, а край ни у кого не режется по столу ровной яркой границей.
 * Цепи карантина сюда не попадают: их набросили поверх кружка целиком, вместе с
 * его стеклом (см. QuarantineSkin).
 *
 * Запекаем один раз в канвас: градиентов у PIXI.Graphics нет, а держать ради
 * этого картинку в ресурсах незачем — стекло целиком описывается числами ниже.
 */

// Где стоит источник света, в долях размера от левого верхнего угла.
const lightX = 0.3;
const lightY = 0.23;

// Блик — тонкая дуга по верхнему левому краю: не пятно на шаре, а отсвет на
// кромке слегка выпуклого значка.
//
// Где идёт её ВНЕШНИЙ край и какова наибольшая толщина — в долях радиуса
// кружка; концы — в градусах (нуль смотрит вправо, отсчёт по часовой при оси y
// вниз, то есть 180° — влево, 270° — вверх). Заострение съедает полосу внутрь,
// а внешний край остаётся на одной окружности — иначе он гуляет и не повторяет
// кромку кружка.
//
// Единица — это ровно кромка: блик лежит на самом краю, без зазора. Резать его
// краю не даёт та же единица — по ней обрезано и всё остальное стекло.
const glintOuter = 1;
const glintWidth = 0.055;
const glintStart = 184;
const glintEnd = 276;
// Едва различимый: сквозь блик должно просвечивать то, на чём он лежит, — лицо
// игрока или карта его статуса. Глухой белой полосой он вырезает из них кусок, и
// это уже не отсвет на стекле, а наклейка поверх.
const glintAlpha = 0.3;
// Насколько дуга сходит на нет к концам: толщина у неё не одна на всю длину —
// в середине полная, а к концам она заостряется. Ровная полоса читается
// нарисованной скобкой, а не отсветом.
//
// Чем меньше число, тем дольше дуга держит полную толщину и тем заметнее выходит
// сама: белый у неё и так в полную силу, и «ярче» её можно сделать только тем,
// сколько её видно.
const glintTaper = 0.75;
// На сколько шагов разбит её внутренний край: он не дуга — расстояние до
// внешнего края вдоль неё меняется.
const glintSteps = 72;

// Тень: доля расстояния от источника света, с которой начинается кайма, ширина
// перехода в неё и её сила — сразу за границей и у самого края кружка. Начинается
// она далеко, поэтому кайма выходит узкой полоской по дальней кромке, а не
// затемнением половины яйца.
//
// Отсчитывается она от света, поэтому вместе с ним и едет: сдвинули источник
// дальше от края — и та же доля даёт кайму шире. До дальнего края кружка отсюда
// 0.836 размера, так что на кайму остаётся полоска в 0.046.
const shadeFrom = 0.79;
const shadeSoft = 0.02;
const shadeAlpha = 0.62;
const shadeEdgeAlpha = 1;

// Рефлекс: светлая кромка по тёмной стороне — свет, отражённый столом. Без него
// кайма читается грязью, а не тенью на круглом. Центр его кольца сдвинут к
// источнику света — тогда кольцо выходит полумесяцем с той стороны, где кайма.
//
// Ширина — в долях радиуса кружка, и отмеряется она внутрь от дальнего края
// кольца, а не долей его радиуса: сдвинутое кольцо у дальней стороны выходит за
// край кружка, и одна и та же доля давала бы полосу тем шире, чем дальше уехал
// свет.
const rimReach = 0.22;
const rimAlpha = 0.18;
const rimPull = 0.34;

let cached: PIXI.Texture | null = null;

// Печём вчетверо крупнее кружка: полоса блика тонкая, и на 256 её при сжатии до
// размера кружка размывает — белое уходит в полутон, и она читается блёклой.
export const sphereShadeTexture = (size = 512): PIXI.Texture => {
	if (cached) return cached;

	const canvas = document.createElement('canvas');
	canvas.width = size;
	canvas.height = size;
	const context = canvas.getContext('2d');
	if (!context) throw new Error('Нет 2d-контекста для светотени кружка');

	const radius = size / 2;
	const lit = {x: size * lightX, y: size * lightY};

	// Рисуем только внутри круга: за его пределами текстура должна остаться
	// прозрачной, иначе сфера вылезет углами за кружок.
	context.save();
	context.beginPath();
	context.ellipse(radius, radius, radius, radius, 0, 0, Math.PI * 2);
	context.clip();

	// Кайма. Центр градиента — у источника света, поэтому темнеет дальняя от него
	// сторона, а до неё кружок остаётся чистого цвета.
	const shade = context.createRadialGradient(lit.x, lit.y, 0, lit.x, lit.y, size);
	shade.addColorStop(0, 'rgba(0, 0, 0, 0)');
	shade.addColorStop(shadeFrom, 'rgba(0, 0, 0, 0)');
	shade.addColorStop(shadeFrom + shadeSoft, `rgba(0, 0, 0, ${shadeAlpha})`);
	shade.addColorStop(1, `rgba(0, 0, 0, ${shadeEdgeAlpha})`);
	context.fillStyle = shade;
	context.fillRect(0, 0, size, size);

	// Рефлекс.
	const rim = {
		x: radius + (lit.x - radius) * rimPull,
		y: radius + (lit.y - radius) * rimPull,
	};
	// Дальний край кольца — самая дальняя от его центра точка кружка.
	const rimFar = radius + Math.hypot(rim.x - radius, rim.y - radius);
	const reflex = context.createRadialGradient(
		rim.x, rim.y, Math.max(0, rimFar - radius * rimReach),
		rim.x, rim.y, rimFar,
	);
	reflex.addColorStop(0, 'rgba(255, 255, 255, 0)');
	reflex.addColorStop(1, `rgba(255, 255, 255, ${rimAlpha})`);
	context.fillStyle = reflex;
	context.fillRect(0, 0, size, size);

	// Блик — последним, поверх всего: он и есть самое яркое место на кружке.
	//
	// Одной фигурой, а не полосой из отрезков: полупрозрачную краску отрезки
	// кладут друг на друга внахлёст (иначе между ними видны швы), и там, где их
	// сошлось трое, от прозрачности не остаётся ничего. Внешний край — дуга,
	// обратный ход — по внутреннему краю, который к концам подбирается к
	// внешнему: там они и смыкаются остриями.
	const from = (glintStart * Math.PI) / 180;
	const to = (glintEnd * Math.PI) / 180;
	const outer = radius * glintOuter;
	context.beginPath();
	context.arc(radius, radius, outer, from, to);
	for (let step = glintSteps; step >= 0; step -= 1) {
		const at = step / glintSteps;
		const angle = from + (to - from) * at;
		const inner = outer - radius * glintWidth * Math.pow(Math.sin(Math.PI * at), glintTaper);
		context.lineTo(radius + Math.cos(angle) * inner, radius + Math.sin(angle) * inner);
	}
	context.closePath();
	context.globalAlpha = glintAlpha;
	context.fillStyle = '#ffffff';
	context.fill();
	context.globalAlpha = 1;

	context.restore();

	cached = PIXI.Texture.from(canvas);
	return cached;
};

/**
 * Цвет метки хода — по кругу, который наматывает её стрелка (см. TurnReticle).
 *
 * Круг за кругом: зелёный, жёлтый, оранжевый, красный. Считаем кругами, а не
 * секундами, и в этом весь смысл — круг это то, что видно глазом, и каждый
 * следующий обязан отличаться от предыдущего. По секундам цвет приходилось
 * привязывать к длине круга на глазок, и стрелка успевала намотать пять
 * оборотов, оставаясь всё тем же зелёным.
 *
 * Красный — последний, дальше цвет не меняется: тревожнее уже не будет, а тон,
 * продолжающий крутиться по кругу, рано или поздно вернулся бы к спокойному
 * зелёному и сказал бы ровно противоположное тому, что происходит. Набирать
 * дальше есть чему и без цвета — с этого момента растёт свечение (см.
 * glowWidthMax в TurnReticle).
 *
 * Круг у стрелки — десять секунд, так что красной метка становится к тридцатой:
 * это самый долгий из отпущенных сроков, дольше стол не ждёт никого.
 */
const lapColors = [
	// Нулевой круг — ровно тот зелёный, каким метка хода была до всяких часов.
	0x00ff00,
	0xffff00,
	0xff8000,
	0xff0000,
];

const finalColor = 0xff0000;

export const turnTimerColor = (laps: number): number => {
	if (laps < 0) return lapColors[0] ?? finalColor;
	return lapColors[Math.floor(laps)] ?? finalColor;
};
